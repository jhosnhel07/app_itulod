/// Ray-casting point-in-polygon test.
bool isInIlocosNorte(LatLng? p) {
  if (p == null) return false;
  final lng = p.longitude, lat = p.latitude;
  if (lng < _minLng || lng > _maxLng || lat < _minLat || lat > _maxLat) return false;
  var inside = false;
  for (var i = 0, j = _boundary.length - 1; i < _boundary.length; j = i++) {
    final (xi, yi) = _boundary[i];
    final (xj, yj) = _boundary[j];
    if ((yi > lat) != (yj > lat) && lng < (xj - xi) * (lat - yi) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/// Booking-time guard: shows a snackbar naming the first place outside the
/// province and returns false; true when every given point is inside.
/// Null points (not chosen yet) are left to the form's own validation.
bool checkServiceArea(BuildContext context, Map<String, LatLng?> places) {
  for (final entry in places.entries) {
    final p = entry.value;
    if (p != null && !isInIlocosNorte(p)) {
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
        content: Text('${entry.key} is outside Ilocos Norte. iTULOD only serves Ilocos Norte.'),
        backgroundColor: const Color(0xFFF04438),
        behavior: SnackBarBehavior.floating,
      ));
      return false;
    }
  }
  return true;
}
